// Regenerates src/geistFont.ts from the Geist latin variable subset that the web app already depends on.
// Run: node packages/auth/scripts/embed-font.mjs. The output is committed, so the package has no build step and the
// Worker bundle needs no file access.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(
  new URL(
    "../../../apps/web/node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2",
    import.meta.url,
  ),
);
const out = fileURLToPath(new URL("../src/geistFont.ts", import.meta.url));
const b64 = readFileSync(src).toString("base64");

writeFileSync(
  out,
  `// Generated by scripts/embed-font.mjs. Do not edit.
// Geist (latin, variable weight). Copyright 2024 The Geist Project Authors (https://github.com/vercel/geist-font).
// Licensed under the SIL Open Font License 1.1 (https://openfontlicense.org). The font is not sold by itself.
export const GEIST_WOFF2 = "data:font/woff2;base64,${b64}";
`,
);
console.log(`wrote ${out} (${b64.length} base64 chars)`);
